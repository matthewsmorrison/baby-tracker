// Generates ios/SharedKit/WHOWeight.swift from lib/whoWeight.ts so the iOS
// app plots exactly the same UK-WHO centile curves as the web app. Run with:
//   node --experimental-strip-types scripts/gen-who-swift.mjs
// Emits the LMS tables verbatim plus cross-check values computed here (the
// Swift port is validated against them in DEBUG builds).
import { readFileSync, writeFileSync } from "fs";

const src = readFileSync("lib/whoWeight.ts", "utf8");

/** Pull a `const NAME: LMS[] = [...]` table out of the TS source verbatim. */
function extractTable(name) {
  const m = src.match(new RegExp(`const ${name}[^=]*= \\[([\\s\\S]*?)\\n\\];`));
  if (!m) throw new Error(`table ${name} not found`);
  return m[1]
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.startsWith("["))
    .map((l) => l.replace(/[\[\],]+$/g, "").replace(/^\[/, "").split(",").map(Number));
}

const tables = {
  BOYS: extractTable("BOYS"),
  GIRLS: extractTable("GIRLS"),
  BOYS_WEEKLY: extractTable("BOYS_WEEKLY"),
  GIRLS_WEEKLY: extractTable("GIRLS_WEEKLY"),
};

// Cross-check values via the real implementation.
const { whoWeightAtZ, whoCentile } = await import("../lib/whoWeight.ts");
const checks = [];
for (const sex of ["boy", "girl"]) {
  for (const [ageDays, z] of [[14, 0], [45, -2.0537], [200, 2.0537], [500, 0.6745]]) {
    checks.push({ sex, ageDays, z, grams: whoWeightAtZ(sex, ageDays, z) });
  }
}
const centileChecks = [
  { sex: "boy", ageDays: 30, weightG: 4400, pct: whoCentile("boy", 30, 4400) },
  { sex: "girl", ageDays: 90, weightG: 5800, pct: whoCentile("girl", 90, 5800) },
];

const swiftRows = (rows) =>
  rows.map((r) => `        LMS(t: ${r[0]}, l: ${r[1]}, m: ${r[2]}, s: ${r[3]}),`).join("\n");

const out = `import Foundation

// GENERATED by scripts/gen-who-swift.mjs from lib/whoWeight.ts — do not edit
// by hand; regenerate after changing the web tables. WHO Child Growth
// Standards weight-for-age LMS parameters, the basis of the UK-WHO (red
// book) charts. A guide for parents, not a substitute for the plotted book.

enum WHOWeight {
    struct LMS { let t: Double; let l: Double; let m: Double; let s: Double }

    /// The nine centile lines printed on UK-WHO charts, with exact z-scores.
    static let ukCentiles: [(label: String, z: Double)] = [
        ("0.4", -2.6521), ("2", -2.0537), ("9", -1.3408), ("25", -0.6745),
        ("50", 0), ("75", 0.6745), ("91", 1.3408), ("98", 2.0537), ("99.6", 2.6521),
    ]

    // Monthly LMS, ages 0–24 completed months.
    static let boysMonthly: [LMS] = [
${swiftRows(tables.BOYS)}
    ]
    static let girlsMonthly: [LMS] = [
${swiftRows(tables.GIRLS)}
    ]
    // Weekly LMS for the steep first 13 weeks.
    static let boysWeekly: [LMS] = [
${swiftRows(tables.BOYS_WEEKLY)}
    ]
    static let girlsWeekly: [LMS] = [
${swiftRows(tables.GIRLS_WEEKLY)}
    ]

    static let daysPerMonth = 30.4375

    /// Linear interpolation across a table at fractional index t.
    private static func interp(_ table: [LMS], _ t: Double) -> (l: Double, m: Double, s: Double) {
        if t <= table.first!.t { let r = table.first!; return (r.l, r.m, r.s) }
        if t >= table.last!.t { let r = table.last!; return (r.l, r.m, r.s) }
        var lower = table[0]
        for row in table.dropFirst() {
            if row.t >= t {
                let span = row.t - lower.t
                let f = span > 0 ? (t - lower.t) / span : 0
                return (
                    lower.l + (row.l - lower.l) * f,
                    lower.m + (row.m - lower.m) * f,
                    lower.s + (row.s - lower.s) * f
                )
            }
            lower = row
        }
        let r = table.last!
        return (r.l, r.m, r.s)
    }

    /// Weekly resolution through 13 weeks (steepest), monthly beyond.
    private static func lmsFor(isBoy: Bool, ageDays: Double) -> (l: Double, m: Double, s: Double) {
        if ageDays <= 91 {
            return interp(isBoy ? boysWeekly : girlsWeekly, ageDays / 7)
        }
        return interp(isBoy ? boysMonthly : girlsMonthly, ageDays / daysPerMonth)
    }

    /// Weight in grams at a z-score for sex + age — one point on a curve.
    static func weightAtZ(isBoy: Bool, ageDays: Double, z: Double) -> Double {
        let (l, m, s) = lmsFor(isBoy: isBoy, ageDays: ageDays)
        let kg = abs(l) < 1e-7 ? m * exp(s * z) : m * pow(1 + l * s * z, 1 / l)
        return (kg * 1000).rounded()
    }

    /// The centile (0–100) a weight sits on, via the inverse LMS transform.
    static func centile(isBoy: Bool, ageDays: Double, weightG: Double) -> Double {
        let (l, m, s) = lmsFor(isBoy: isBoy, ageDays: ageDays)
        let ratio = weightG / 1000 / m
        let z = abs(l) < 1e-7 ? log(ratio) / s : (pow(ratio, l) - 1) / (l * s)
        return normalCdf(z) * 100
    }

    /// Standard normal CDF (Zelen & Severo approximation).
    private static func normalCdf(_ z: Double) -> Double {
        let t = 1 / (1 + 0.2316419 * abs(z))
        let d = 0.3989423 * exp(-z * z / 2)
        let p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.7814779 + t * (-1.821256 + t * 1.3302744))))
        return z > 0 ? 1 - p : p
    }

    /// Cross-checks computed by the generator with the web implementation —
    /// asserted in DEBUG so the two apps can never silently diverge.
    static let crossChecks: [(isBoy: Bool, ageDays: Double, z: Double, grams: Double)] = [
${checks.map((c) => `        (isBoy: ${c.sex === "boy"}, ageDays: ${c.ageDays}, z: ${c.z}, grams: ${c.grams}),`).join("\n")}
    ]
    static let centileChecks: [(isBoy: Bool, ageDays: Double, weightG: Double, pct: Double)] = [
${centileChecks.map((c) => `        (isBoy: ${c.sex === "boy"}, ageDays: ${c.ageDays}, weightG: ${c.weightG}, pct: ${c.pct}),`).join("\n")}
    ]

    static func verify() -> Bool {
        for c in crossChecks where abs(weightAtZ(isBoy: c.isBoy, ageDays: c.ageDays, z: c.z) - c.grams) > 1 {
            return false
        }
        for c in centileChecks where abs(centile(isBoy: c.isBoy, ageDays: c.ageDays, weightG: c.weightG) - c.pct) > 0.1 {
            return false
        }
        return true
    }
}
`;

writeFileSync("ios/SharedKit/WHOWeight.swift", out);
console.log("WHOWeight.swift written:", Object.values(tables).map((t) => t.length).join("/"), "rows");
